const closureInstant = (agent: AgentRecord): string =>
  agent.closedAt ?? agent.lastEventAt;

/** Pick the next agent name. A name means exactly one agent at a time, so a name with a live holder is never issued. Beyond that: prefer a name this Hive has never used, traversing fresh names in a stable pseudorandom order derived from the Hive instance. Different ordinary runs therefore get different name sequences without a retry changing its candidate mid-spawn. Fall back to the least-recently-closed name only once no fresh name is left. Across a few hundred names reuse is therefore legal but vanishingly rare — which is the point. The user's scrollback still says "maya reported X", and the odds that a *new* maya exists to misreceive "maya, follow up on X" stay near zero, while closure is durably recorded so history can always name the agent that closed. When every pool name has a live holder there is nothing honest to return. Numeric suffixes (maya-2) are never minted, and taking a live agent's name would create exactly the ambiguity this design exists to prevent. Refuse, and say the pool needs expanding. */
export function selectAgentName(
  agents: AgentRecord[],
  unavailable: ReadonlySet<string> = new Set(),
  instanceSeed: string = hiveInstanceSuffix(),
): string {
  const live = new Set(agents.filter(isLiveAgent).map((agent) => agent.name));
  const everUsed = new Set(agents.map((agent) => agent.name));
  const taken = (name: string): boolean =>
    live.has(name) || unavailable.has(name);

  const fresh = NAME_POOL.filter(
    (candidate) => !everUsed.has(candidate) && !taken(candidate),
  )
    .map((name) => ({
      name,
      rank: createHash("sha256")
        .update(instanceSeed)
        .update("\0")
        .update(name)
        .digest("hex"),
    }))
    .sort(
      (a, b) => a.rank.localeCompare(b.rank) || a.name.localeCompare(b.name),
    )
    .at(0);
  if (fresh !== undefined) return fresh.name;

  const inPool = new Set<string>(NAME_POOL);
  const closed = agents
    .filter((agent) => inPool.has(agent.name) && !taken(agent.name))
    .sort((a, b) => closureInstant(a).localeCompare(closureInstant(b)));
  const [available] = closed;
  if (available !== undefined) return available.name;

  throw new Error(
    `Hive agent name pool exhausted: all ${NAME_POOL.length} names are held by ` +
      "a live or spawning agent. Hive never reuses a live name and never " +
      "appends a numeric suffix, so this spawn is refused. Close an agent, or " +
      "expand NAME_POOL in src/daemon/spawn/agent-name-selection.ts.",
  );
}
